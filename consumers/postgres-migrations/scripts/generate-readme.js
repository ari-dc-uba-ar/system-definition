const {readFileSync, writeFileSync} = require("node:fs");
const {resolve} = require("node:path");

const consumerRoot = resolve(__dirname, "..");
const examplesPath = resolve(consumerRoot, "test/fixtures/cli-doc-examples.json");
const readmePath = resolve(consumerRoot, "README.md");
const examples = JSON.parse(readFileSync(examplesPath, "utf8"));

function shellQuote(value) {
    return /^[A-Za-z0-9_./:-]+$/u.test(value) ? value : JSON.stringify(value);
}

function commandLine(example) {
    return ["postgres-migrations", example.command, ...example.args].map(shellQuote).join(" ");
}

function resultLabel(example) {
    if (example.result.ok) return "success";
    return example.result.problems.map((one) => one.messageKey).join(", ");
}

const rows = examples.map((example) =>
    `| ${example.title} | \`${commandLine(example)}\` | ${example.exitCode} | \`${resultLabel(example)}\` |`,
);

const generated = `# PostgreSQL migrations consumer\n\n<!-- GENERATED by scripts/generate-readme.js from test/fixtures/cli-doc-examples.json. DO NOT EDIT BY HAND. -->\n\nConsumer package for immutable migration/release artifacts and PostgreSQL integration. It is built and tested separately from the root TypeScript program; production code imports the public \`system-definition\` package API rather than private root sources.\n\n## Verification commands\n\nFrom the repository root:\n\n\`\`\`sh\nnpm --prefix consumers/postgres-migrations test\nnpm --prefix consumers/postgres-migrations run test-integration\nnpm --prefix consumers/postgres-migrations run docs:check\n\`\`\`\n\nThe integration command is intentionally strict: it talks to a real PostgreSQL server and requires \`server_version_num = 180006\` (PostgreSQL 18.6). A missing client/server or any other PostgreSQL version is a failing integration run, not a skipped success. It also runs the T22 authoring matrix on the same immutable plan/artifact resolver and transactional runner: \`generated-only\`, \`manual\`, \`mixed\`, and a blocking rollback case with zero activations.\n\nAuthoring commands are non-interactive unless the explicit resolver flow is invoked. Pending authoring in non-interactive mode returns a non-zero result with \`migration.authoringPending\`; deployment/apply/verify never waits for stdin to resolve an authoring decision.\n\n## CLI result examples\n\nThese examples are generated from the same fixture exercised by the CLI contract tests. Exit code \`0\` means complete success; \`2\` is invalid input/configuration, \`3\` is verification/gate blocking, and \`4\` is an operational or unknown-commit failure.\n\n| Case | Command | Exit | Result |\n| --- | --- | ---: | --- |\n${rows.join("\n")}\n\n## Checkout/bootstrap behavior\n\nThe checkout declares \`system-definition\` as a local package dependency. \`prebuild\`/\`pretest\` run \`scripts/bootstrap-repository.js\`, which only links this repository root into the root \`node_modules\`; it performs no network install. The root suite compiles the public package before entering the consumer suite.\n\nPublished SQL resources are byte-addressed UTF-8/LF artifacts. They are validated and never normalized on load.\n`;

function normalizeLineEndings(value) {
    return value.replace(/\r\n?/gu, "\n");
}

if (process.argv.includes("--check")) {
    const current = readFileSync(readmePath, "utf8");
    if (normalizeLineEndings(current) !== generated) {
        process.stderr.write("consumers/postgres-migrations/README.md is stale; run npm --prefix consumers/postgres-migrations run docs:generate\n");
        process.exitCode = 1;
    }
} else {
    writeFileSync(readmePath, generated);
}
